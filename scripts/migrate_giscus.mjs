#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(new URL(".", import.meta.url).pathname, "..");
const OUT = resolve(ROOT, "scripts", "out");
const CACHE = resolve(OUT, "giscus-discussions");
const OWNER = "Meaow-Technologies";
const REPO = "TWATF-Reader";
const TOKEN = process.env.GITHUB_DISCUSSIONS_TOKEN || process.env.DISCUSSIONS_TOKEN;
const APPLY = process.argv.includes("--apply");
const LIMIT = Number(process.argv.find((arg) => arg.startsWith("--limit="))?.split("=")[1] || Infinity);

if (!TOKEN) {
  console.error("Set GITHUB_DISCUSSIONS_TOKEN before running the migration.");
  process.exit(1);
}

const query = `
query($owner: String!, $repo: String!, $cursor: String) {
  repository(owner: $owner, name: $repo) {
    discussions(first: 100, after: $cursor) {
      pageInfo { hasNextPage endCursor }
      nodes { number title body }
    }
  }
}`;

const commentsQuery = `
query($owner: String!, $repo: String!, $number: Int!, $cursor: String) {
  repository(owner: $owner, name: $repo) {
    discussion(number: $number) {
      comments(first: 100, after: $cursor) {
        pageInfo { hasNextPage endCursor }
        nodes {
          databaseId
          author { login avatarUrl ... on User { databaseId } }
          body
          createdAt
          replies(first: 100) {
            nodes {
              databaseId
              author { login avatarUrl ... on User { databaseId } }
              body
              createdAt
            }
          }
        }
      }
    }
  }
}`;

async function github(queryText, variables) {
  const response = await fetch("https://api.github.com/graphql", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${TOKEN}`,
      "Content-Type": "application/json",
      "User-Agent": "TWATF-Reader Giscus migration",
    },
    body: JSON.stringify({ query: queryText, variables }),
  });
  if (!response.ok) throw new Error(`GitHub API returned ${response.status}`);
  const payload = await response.json();
  if (payload.errors?.length) throw new Error(JSON.stringify(payload.errors));
  return payload.data;
}

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function chapterFromTitle(title) {
  const match = String(title).match(/twatf-(first|revised)-chapter-(\d+)/i);
  return match ? `${match[1]}:${Number(match[2])}` : null;
}

function date(value) {
  return value ? value.replace("T", " ").replace("Z", "").slice(0, 19) : null;
}

function collectComment(records, users, discussion, node, parentId = null) {
  const providerId = node.author?.databaseId == null ? `deleted:${node.databaseId}` : String(node.author.databaseId);
  const userId = `github:${providerId}`;
  users.set(userId, {
    id: userId,
    providerId,
    login: node.author?.login || "deleted-user",
    displayName: node.author?.login || "Deleted user",
    avatarUrl: node.author?.avatarUrl || null,
  });
  records.push({
    legacyId: `gh:${discussion.chapter}:${node.databaseId}`,
    chapter: discussion.chapter,
    userId,
    parentLegacyId: parentId === null ? null : `gh:${discussion.chapter}:${parentId}`,
    body: node.body || "",
    createdAt: date(node.createdAt),
  });
}

async function getDiscussions() {
  const discussions = [];
  let cursor = null;
  do {
    const data = await github(query, { owner: OWNER, repo: REPO, cursor });
    const page = data.repository.discussions;
    discussions.push(...page.nodes.map((node) => ({ ...node, chapter: chapterFromTitle(node.title) })).filter((node) => node.chapter));
    cursor = page.pageInfo.hasNextPage ? page.pageInfo.endCursor : null;
  } while (cursor && discussions.length < LIMIT);
  return discussions.slice(0, LIMIT);
}

async function getComments(discussion) {
  const cachePath = resolve(CACHE, `${discussion.number}.json`);
  if (existsSync(cachePath)) return JSON.parse(readFileSync(cachePath, "utf8"));
  let cursor = null;
  const nodes = [];
  do {
    const data = await github(commentsQuery, {
      owner: OWNER,
      repo: REPO,
      number: discussion.number,
      cursor,
    });
    const page = data.repository.discussion?.comments;
    if (!page) break;
    nodes.push(...page.nodes);
    cursor = page.pageInfo.hasNextPage ? page.pageInfo.endCursor : null;
  } while (cursor);
  mkdirSync(CACHE, { recursive: true });
  writeFileSync(cachePath, JSON.stringify(nodes), "utf8");
  return nodes;
}

function buildSql(users, comments) {
  const lines = [
    "-- Generated by scripts/migrate_giscus.mjs. Review before applying.",
    "PRAGMA foreign_keys = ON;",
    "",
  ];
  for (const user of users.values()) {
    lines.push(
      `INSERT OR IGNORE INTO users (id, provider, provider_user_id, login, display_name, avatar_url, is_legacy) VALUES (${sql(user.id)}, 'github', ${sql(user.providerId)}, ${sql(user.login)}, ${sql(user.displayName)}, ${sql(user.avatarUrl)}, 1);`,
    );
  }
  for (const comment of comments.filter((item) => item.parentLegacyId === null)) {
    lines.push(
      `INSERT OR IGNORE INTO comments (chapter, user_id, parent_id, body, is_legacy, legacy_id, created_at) VALUES (${sql(comment.chapter)}, ${sql(comment.userId)}, NULL, ${sql(comment.body)}, 1, ${sql(comment.legacyId)}, ${sql(comment.createdAt)});`,
    );
  }
  for (const comment of comments.filter((item) => item.parentLegacyId !== null)) {
    lines.push(
      `INSERT OR IGNORE INTO comments (chapter, user_id, parent_id, body, is_legacy, legacy_id, created_at) VALUES (${sql(comment.chapter)}, ${sql(comment.userId)}, (SELECT id FROM comments WHERE legacy_id = ${sql(comment.parentLegacyId)}), ${sql(comment.body)}, 1, ${sql(comment.legacyId)}, ${sql(comment.createdAt)});`,
    );
  }
  return `${lines.join("\n")}\n`;
}

const discussions = await getDiscussions();
const users = new Map();
const comments = [];
for (const discussion of discussions) {
  const nodes = await getComments(discussion);
  for (const node of nodes) {
    collectComment(comments, users, discussion, node);
    for (const reply of node.replies?.nodes || []) {
      collectComment(comments, users, discussion, reply, Number(node.databaseId));
    }
  }
}

console.log(`Matched ${discussions.length} discussions, ${comments.length} comments, and ${users.size} users.`);
if (!APPLY) {
  console.log("Dry run complete. Re-run with --apply to write scripts/out/migrate_giscus.sql.");
  process.exit(0);
}
mkdirSync(OUT, { recursive: true });
writeFileSync(resolve(OUT, "migrate_giscus.sql"), buildSql(users, comments), "utf8");
console.log("Wrote scripts/out/migrate_giscus.sql.");
